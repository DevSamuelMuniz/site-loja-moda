/** Paleta de cores disponivel no catalogo demonstrativo. */
const palette = {
  preto: { name: 'Preto', hex: '#111111' },
  branco: { name: 'Branco', hex: '#FFFFFF' },
  bege: { name: 'Bege', hex: '#DCCFBB' },
  azul: { name: 'Azul', hex: '#2F4468' },
  verde: { name: 'Verde', hex: '#3F5C4A' },
  offWhite: { name: 'Off-white', hex: '#F1EEE8' },
  areia: { name: 'Areia', hex: '#C9B79C' },
  grafite: { name: 'Grafite', hex: '#3A3A3E' },
  caramelo: { name: 'Caramelo', hex: '#9A6B3F' },
  vinho: { name: 'Vinho', hex: '#5C2B33' },
} as const;

type PaletteKey = keyof typeof palette;

/** Slug de arquivo da cor: `offWhite` -> `off-white`. */
function colorSlug(key: PaletteKey): string {
  return key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

/**
 * Monta as variantes de cor de um produto.
 * O SKU de cada cor deriva do SKU base, e a imagem aponta para a arte daquela cor.
 */
function buildColors(
  slug: string,
  skuBase: string,
  keys: PaletteKey[],
  stocks: number[],
): ProductColor[] {
  return keys.map((key, index) => ({
    name: palette[key].name,
    slug: colorSlug(key),
    hex: palette[key].hex,
    image: colorArtwork(slug, colorSlug(key)),
    sku: `${skuBase}-${String(index + 1).padStart(2, '0')}`,
    stock: stocks[index] ?? 0,
  }));
}

